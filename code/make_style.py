"""Build style.css with the Tracy Hand font embedded (base64), for the MyST site.

Embedding avoids any question of how the theme resolves font URLs.
Run from the repo root:  python code/make_style.py
"""
import base64
from pathlib import Path

font = Path("fonts/TracyHand-Geo-70.ttf")
b64 = base64.b64encode(font.read_bytes()).decode("ascii")

css = f"""/* Generated by code/make_style.py. Edit that script, not this file. */
@font-face {{
  font-family: "Tracy Hand";
  src: url(data:font/ttf;base64,{b64}) format("truetype");
  font-weight: normal;
  font-style: normal;
  font-display: swap;
}}

/* Handwriting everywhere except code and math. */
body,
body *:not(code):not(pre):not(pre *):not(.katex):not(.katex *) {{
  font-family: "Tracy Hand", system-ui, sans-serif !important;
}}
"""
Path("style.css").write_text(css, encoding="utf-8")
print(f"wrote style.css ({len(css) // 1024} KB)")
